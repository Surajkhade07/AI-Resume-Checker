import { useState } from 'react'
import { CATEGORY_ICONS } from '../lib/scoreHelpers.js'

function RecommendationCard({ rec }) {
  const [open, setOpen] = useState(true)
  const priorityClass = `rec-priority-${rec.priority_value || 'medium'}`
  const catIcon = CATEGORY_ICONS[rec.category] || '💡'

  return (
    <div className={`rec-card ${priorityClass}`}>
      <div className="rec-card-header" onClick={() => setOpen((v) => !v)}>
        <div className="rec-card-title-group">
          <span className="rec-priority-icon">{rec.priority_icon || '🟡'}</span>
          <div>
            <div className="rec-meta-row">
              <span className={`rec-badge badge-${rec.priority_value || 'medium'}`}>
                {rec.priority_label || 'Priority'}
              </span>
              <span className="rec-cat-badge">
                {catIcon} {rec.category ? rec.category.replace('_', ' ').toUpperCase() : 'GENERAL'}
              </span>
              {rec.impact_score > 0 && (
                <span className="rec-impact-badge">
                  📈 Up to +{Math.round(rec.impact_score)} pts
                </span>
              )}
            </div>
            <h4 className="rec-title">{rec.title}</h4>
          </div>
        </div>
        <button className="expander-toggle" aria-label="Toggle details">
          {open ? '▴' : '▸'}
        </button>
      </div>

      {open && (
        <div className="rec-card-body">
          <p className="rec-description">{rec.description}</p>
          {(rec.action_items || []).length > 0 && (
            <div className="rec-actions-box">
              <strong className="rec-actions-heading">Recommended Action Steps:</strong>
              <ul className="rec-actions-list">
                {rec.action_items.map((item, idx) => (
                  <li key={idx} className="rec-action-item">
                    <span className="rec-checkbox">✓</span>
                    <span>{item}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
      )}
    </div>
  )
}

export default function Recommendations({ analysis }) {
  const recs = analysis.recommendations || []
  const summary = analysis.recommendation_summary || ''
  const improvement = analysis.estimated_improvement || 0
  const fallbackSuggestions = analysis.suggestions || []

  const [activeFilter, setActiveFilter] = useState('all')

  if (recs.length === 0 && fallbackSuggestions.length === 0) {
    return (
      <section className="panel">
        <h3 className="panel-title">💡 Strategic Recommendations</h3>
        <div className="alert good">
          <strong>🎉 Excellent Profile!</strong>
          <p>No critical recommendations were triggered. Your resume is well aligned for ATS scanners.</p>
        </div>
      </section>
    )
  }

  // Handle fallback suggestions if recommendations array is empty
  const allItems = recs.length > 0 ? recs : fallbackSuggestions.map((s, i) => ({
    title: `Recommendation #${i + 1}`,
    description: s,
    priority_icon: '🟠',
    priority_label: 'Suggested',
    priority_value: 'medium',
    impact_score: 3.0,
    category: 'general',
    action_items: [s],
  }))

  const filtered = activeFilter === 'all'
    ? allItems
    : allItems.filter((r) => r.priority_value === activeFilter)

  const criticalCount = allItems.filter((r) => r.priority_value === 'critical').length
  const highCount = allItems.filter((r) => r.priority_value === 'high').length

  return (
    <section className="panel">
      <div className="panel-header-row">
        <div>
          <h3 className="panel-title">💡 Prioritized Recommendations Engine</h3>
          <p className="panel-caption">
            {summary || `Found ${allItems.length} actionable recommendation(s) generated by the multi-domain analysis engine.`}
          </p>
        </div>
        {improvement > 0 && (
          <div className="improvement-potential-pill">
            <span className="pill-sub">Potential Boost</span>
            <strong className="pill-val">+{Math.round(improvement)} pts</strong>
          </div>
        )}
      </div>

      <div className="rec-filter-bar">
        <button
          className={`filter-btn ${activeFilter === 'all' ? 'active' : ''}`}
          onClick={() => setActiveFilter('all')}
        >
          All ({allItems.length})
        </button>
        {criticalCount > 0 && (
          <button
            className={`filter-btn btn-crit ${activeFilter === 'critical' ? 'active' : ''}`}
            onClick={() => setActiveFilter('critical')}
          >
            🔴 Critical ({criticalCount})
          </button>
        )}
        {highCount > 0 && (
          <button
            className={`filter-btn btn-high ${activeFilter === 'high' ? 'active' : ''}`}
            onClick={() => setActiveFilter('high')}
          >
            🟠 High ({highCount})
          </button>
        )}
        <button
          className={`filter-btn ${activeFilter === 'medium' ? 'active' : ''}`}
          onClick={() => setActiveFilter('medium')}
        >
          🟡 Medium
        </button>
        <button
          className={`filter-btn ${activeFilter === 'low' ? 'active' : ''}`}
          onClick={() => setActiveFilter('low')}
        >
          🟢 Low
        </button>
      </div>

      <div className="rec-cards-container">
        {filtered.map((rec, i) => (
          <RecommendationCard key={i} rec={rec} />
        ))}
      </div>
    </section>
  )
}

